//! 可选的一致读取能力；快照对象拥有后端所需的锁、Guard 或版本资源。
use crate::GraphBase;

/// 获取一个拓扑一致的只读图访问对象，不要求复制存储。
/// 后端不得仅因为返回了共享引用就宣称拓扑一致；内部并发修改也必须被隔离。
/// 此协议不自动保证属性值固定，不自动继承底层所有图能力。
pub trait GraphSnapshot: GraphBase {
    /// 获取读取资源失败的后端错误，例如锁不可用或所需版本已不可读。
    type Error;
    /// 拓扑固定的访问对象，身份类型与源图一致；由它实现实际可保证的访问能力。
    /// 对象及其派生借用存活期间必须保留相应版本或读取资源。
    type View<'a>: GraphBase<NodeId = Self::NodeId, EdgeId = Self::EdgeId>
    where
        Self: 'a;
    /// true 表示此实现的每次成功快照同时固定可读业务数据和拓扑。
    /// false 仅承诺拓扑一致；调用方不能据此假定属性过滤或搜索具有可重复结果。
    /// 不包含调用方闭包捕获的可变外部状态；后端须文档说明其读取与隔离机制。
    const DATA_STABLE: bool;

    /// 获取一次一致读取对象；成功返回的全部拓扑能力须对应同一逻辑状态。
    /// Err 不产生可用快照，不改变图拓扑或数据，已取得的临时资源由后端释放。
    /// 不保证非阻塞；锁等待、重入和超时策略由具体后端明确。
    /// 多次调用可取得不同状态；快照间 ID 不得绕过底层身份有效期规则混用。
    /// 释放 View 后释放其读取资源，派生引用受 View 生命周期限制。
    fn snapshot(&self) -> Result<Self::View<'_>, Self::Error>;
}
