//! 独立只读投影能力；不依赖完整 Weight 或特定元素引用协议。

/// 将当前访问对象投影为由 P 标识的只读表示。
///
/// P 是投影类别，不要求它等同于输出类型。实现可返回普通字段引用，
/// 也可返回由多个字段借用组合的 View；不要求源对象先提供完整 Weight。
/// 不自动为 NodeRef、EdgeRef 或其包装提供实现，是否支持由后端决定。
///
/// 调用形式为 Project::<P>::project(&reference)。若输出借用源对象，
/// 调用方必须保留源对象及其 Guard，不能将输出借用延长到源对象析构之后。
pub trait Project<P> {
    /// 本次投影的输出表示，可借用 self；不强制 Deref、Copy 或 Clone。
    /// 借用输出不得比本次 self 借用存活更久，不能绕过源对象的 Guard。
    type Output<'a>
    where
        Self: 'a;

    /// 从当前对象投影，不消费 self，不修改业务数据、身份或拓扑。
    ///
    /// 成功返回 Some(output)；源对象不属于 P 对应的类型或不具备所需字段时
    /// 返回 None，不改变源对象状态。None 不表示 I/O、锁获取或存储损坏错误；
    /// 这些访问失败须在取得源对象的能力边界处理，不由本协议编码。
    ///
    /// 同一源状态及投影类别应产生语义一致的结果。本协议不承诺额外快照一致性，
    /// 并发与锁约束沿用源访问对象；Guard 仍由源对象拥有。
    fn project(&self) -> Option<Self::Output<'_>>;
}
