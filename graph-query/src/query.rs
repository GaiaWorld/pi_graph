//! 后端类型化查询执行能力；查询描述不等于 Iterator::filter。
use graph_core::GraphBase;

/// 执行 Q 描述的节点查询，后端自行选择索引、扫描或组合策略。
/// Q 由后端及调用者定义，不要求闭包、统一属性枚举或跨后端 DSL。
/// 边的方向、端口及锚点范围若适用，由查询描述编码并在该实现的契约中说明。
pub trait NodeSearch<Q: ?Sized>: GraphBase {
    /// 查询验证、执行准备或索引不可用的错误，不以空结果冒充失败。
    type Error;
    /// 同时借用图和 query 的标准 ID 迭代器；每个匹配身份至多一次。
    /// 不隐含排序，结果顺序由后端契约决定；不支持逐项 I/O 错误。
    type Iter<'a>: Iterator<Item = Self::NodeId>
    where
        Self: 'a,
        Q: 'a;

    /// query：借用的类型化查询描述；图及查询借用覆盖整个返回迭代器的使用期。
    /// 成功返回满足条件的可见身份，无匹配返回空迭代器；查询无效或无法执行返回 Err。
    /// 索引与扫描必须具有相同匹配语义，不得泄漏当前视图之外的身份。
    /// 不修改图业务数据或拓扑；后端可维护不影响结果的内部查询缓存。
    /// 调用方保证迭代期间拓扑及查询相关属性稳定，或使用提供这些保证的 Snapshot。
    /// 拓扑快照不自动固定属性结果；后端须说明搜索读取的一致性要求。
    /// 首版为内存型结果能力：可正常报告的执行错误须在返回迭代器之前处理；
    /// 需要逐项错误的远端或磁盘流后端应另提供 fallible stream 能力。
    /// 不为 Reversed / Filtered 自动转发本能力，适配实现须处理方向与可见性。
    fn search_nodes<'a>(&'a self, query: &'a Q) -> Result<Self::Iter<'a>, Self::Error>;
}

